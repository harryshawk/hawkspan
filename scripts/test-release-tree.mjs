#!/usr/bin/env node

import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createReleaseManifest, RELEASE_MANIFEST_PATH, verifyReleaseTree } from "./release-tree.mjs";

function fixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "hawkspan-release-tree-"));
  fs.mkdirSync(path.join(root, "scripts"));
  fs.writeFileSync(path.join(root, "README.md"), "public fixture\n");
  fs.writeFileSync(path.join(root, "scripts.txt"), "sorting fixture\n");
  fs.writeFileSync(path.join(root, "scripts", "tool.mjs"), "export const safe = true;\n");
  const manifest = createReleaseManifest(root);
  fs.mkdirSync(path.join(root, "release"));
  fs.writeFileSync(path.join(root, RELEASE_MANIFEST_PATH), `${JSON.stringify(manifest, null, 2)}\n`);
  return { root, manifest };
}

{
  const { root, manifest } = fixture();
  try {
    assert.deepEqual(verifyReleaseTree(root), { release_id: manifest.release_id, file_count: 3 });
    fs.mkdirSync(path.join(root, ".git"));
    fs.writeFileSync(path.join(root, ".git", "private-internal"), "ignored git metadata\n");
    fs.mkdirSync(path.join(root, "scripts", "__pycache__"));
    fs.writeFileSync(path.join(root, "scripts", "__pycache__", "tool.cpython-310.pyc"), "generated bytecode\n");
    fs.writeFileSync(path.join(root, "scripts", "standalone.pyc"), "generated bytecode\n");
    assert.deepEqual(verifyReleaseTree(root), { release_id: manifest.release_id, file_count: 3 });
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
}

for (const mutation of [
  (root) => fs.appendFileSync(path.join(root, "README.md"), "changed\n"),
  (root) => fs.writeFileSync(path.join(root, "unexpected.txt"), "extra\n"),
  (root) => fs.rmSync(path.join(root, "scripts", "tool.mjs")),
]) {
  const { root } = fixture();
  try {
    mutation(root);
    assert.throws(() => verifyReleaseTree(root), /does not match/);
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
}

{
  const { root } = fixture();
  try {
    fs.symlinkSync("README.md", path.join(root, "alias"));
    assert.throws(() => verifyReleaseTree(root), /unsupported entry/);
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
}

process.stdout.write("hawkspan release tree tests passed\n");
